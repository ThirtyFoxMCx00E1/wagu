#!/bin/bash
# MP 4.11: builds src/ui/filepick_dex.h (the FilePick Fragment, see src/ui/filepick.cpp).
#   JAVA_HOME=~/jdk ANDROID_JAR=android.jar (API 26+) R8_JAR=r8.jar bash tools/filepick/build.sh
set -e
cd "$(dirname "$0")"
export PATH=${JAVA_HOME:-$HOME/jdk}/bin:$PATH
JAR=${ANDROID_JAR:-$HOME/dextools/android.jar}; R8=${R8_JAR:-$HOME/dextools/r8.jar}
rm -rf build; mkdir -p build/classes build/dex
javac --release 8 -Xlint:-options -cp "$JAR" -d build/classes src/com/thirtyfox/mp/FilePick.java
java -cp "$R8" com.android.tools.r8.D8 --min-api 21 --release --lib "$JAR" --output build/dex $(find build/classes -name '*.class')
python3 - <<'PY'
d = open('build/dex/classes.dex', 'rb').read()
rows = [', '.join('0x%02x' % b for b in d[i:i + 20]) for i in range(0, len(d), 20)]
open('../../src/ui/filepick_dex.h', 'w').write('// generated by tools/filepick/build.sh (FilePick.java) - do not edit\n#pragma once\nstatic const unsigned char k_FilePickDex[%d] = {\n    %s\n};\n' % (len(d), ',\n    '.join(rows)))
PY
ls -la ../../src/ui/filepick_dex.h
