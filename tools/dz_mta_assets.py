#!/usr/bin/env python3
"""3.59: pack the original MTA DayZ art (github.com/ThirtyFoxMCx00E1/mtadayz, DayZ/gui) into the
Project Day Z Legacy atlases + src/mp_dayz_atlas.h (UV rects).
  python3 tools/dz_mta_assets.py ../mtadayz
Credits: MTA DayZ by the NullSystemWorks team / original authors (see their contributors.txt)."""
import os, sys
from PIL import Image
SRC = os.path.join(sys.argv[1] if len(sys.argv) > 1 else '../mtadayz', 'DayZ', 'gui')
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'assets', 'MP')
def L(p): return Image.open(os.path.join(SRC, p)).convert('RGBA')
def fit(im, w, h):
    im = im.copy(); im.thumbnail((w, h), Image.LANCZOS)
    c = Image.new('RGBA', (w, h), (0, 0, 0, 0)); c.alpha_composite(im, ((w - im.width) // 2, (h - im.height) // 2)); return c
def save(im, name, colors=None):
    p = os.path.join(OUT, name)
    if colors: im = im.quantize(colors=colors, method=Image.FASTOCTREE, dither=Image.NONE)
    im.save(p, optimize=True); print(name, im.size, os.path.getsize(p))
hdr = ['// generated by tools/dz_mta_assets.py - the original MTA DayZ art in the Project Day Z Legacy atlases', '#pragma once']

# ---- items: dz_items.png 8x8 x 96 px, cell = item id; real MTA icons where we have one, else the generated icon
ICON = {1:'knife',2:'machete',3:'m1911',4:'revolver',5:'remington',6:'spaz',7:'pdw',8:'bizon',9:'mp5a5',10:'ak47',11:'m4',12:'cz550',13:'dmr',14:'ak47',
        15:'9x19',16:'shotgun',17:'9x18',18:'m4mag',19:'sniper',20:'bakedbeans',21:'mre',22:'pasta',23:'cola',24:'bottle',25:'pepsi',26:'chest',27:'bandage',
        28:'antibiotics',29:'painkillers',30:'patrol',31:'czech',32:'alice',33:'helmet',38:'gps',39:'canister',40:'toolbox',41:'map',42:'watch',43:'trashtincan',
        44:'emptybottle',45:'glass',46:'morphine',47:'epipen',48:'bloodbag',49:'compass',
        50:'heatpack',51:'wheel',52:'engine',53:'parts',54:'gas',55:'keycard',56:'clothes',57:'clothes',58:'clothes',59:'clothes',60:'sardines',61:'stew',62:'binoculars',63:'rangefinder'}
C = 96
gen = Image.open(os.path.join(OUT, 'dz_items.png')).convert('RGBA') if os.path.exists(os.path.join(ROOT, 'tools', 'dz_items_gen.png')) is False else Image.open(os.path.join(ROOT, 'tools', 'dz_items_gen.png')).convert('RGBA')
if not os.path.exists(os.path.join(ROOT, 'tools', 'dz_items_gen.png')): gen.save(os.path.join(ROOT, 'tools', 'dz_items_gen.png'))
atlas = Image.new('RGBA', (C * 8, C * 8), (0, 0, 0, 0))
TINT = {14: (255, 200, 40), 57: (120, 150, 80), 58: (70, 110, 50), 59: (150, 120, 90)}
for i in range(1, 64):
    x, y = (i % 8) * C, (i // 8) * C
    f = ICON.get(i)
    if f and os.path.exists(os.path.join(SRC, 'gear', 'icons', f + '.png')):
        im = fit(L('gear/icons/%s.png' % f), C - 6, C - 6)
        if i in TINT:   # gold AK / camo / ghillie / survivor clothes
            r, g, b = TINT[i]; px = im.load()
            for yy in range(im.height):
                for xx in range(im.width):
                    p = px[xx, yy]
                    if p[3]: l = (p[0] + p[1] + p[2]) // 3; px[xx, yy] = (min(255, l * r // 160), min(255, l * g // 160), min(255, l * b // 160), p[3])
        atlas.alpha_composite(im, (x + 3, y + 3))
    elif i < 50:
        atlas.alpha_composite(gen.crop((x, y, x + C, y + C)), (x, y))
save(atlas, 'dz_items.png')

# ---- status: dz_status.png 8 cols x 128 px
cells = []
cells += [('BLOOD%d' % k, 'status/blood/%d.png' % v) for k, v in enumerate((2000, 4000, 6000, 8000, 10000, 12000))]
cells += [('FOOD%d' % k, 'status/hunger/%d.png' % v) for k, v in enumerate((0, 20, 40, 60, 80, 100))]
cells += [('DRINK%d' % k, 'status/thirst/%d.png' % v) for k, v in enumerate((0, 20, 40, 60, 80, 100))]
cells += [('TEMP%d' % k, 'status/temperature/%d.png' % k) for k in range(5)]
cells += [('TARROW%d' % k, 'status/temperature/temperature_%d.png' % k) for k in range(7)]
cells += [('HUM%d' % k, 'status/humanity/%d.png' % k) for k in range(6)]
cells += [('LEVEL%d' % (k + 1), 'status/misc/level_%d.png' % (k + 1)) for k in range(5)]
cells += [('BLOOD_BORDER', 'status/blood/blood_border.png'), ('FOOD_BORDER', 'status/hunger/food_border.png'), ('DRINK_BORDER', 'status/thirst/thirst_border.png'),
          ('TEMP_BORDER', 'status/temperature/temperature_border.png'), ('DROP', 'status/blood/drop.png'), ('INFECTION', 'status/blood/infection.png'),
          ('BONE', 'status/misc/brokenbone.png'), ('EYE', 'status/misc/eye.png'), ('EAR', 'status/misc/sound.png'), ('MEDIC', 'status/misc/medic.png'),
          ('HELMET', 'status/misc/helmet.png'), ('SPLAT', 'status/misc/background.png'), ('HOURGLASS', 'status/misc/hourglass.png'), ('CIRCLE', 'status/misc/circle.png')]
S = 128; cols = 8; rows = (len(cells) + cols - 1) // cols
st = Image.new('RGBA', (S * cols, S * rows), (0, 0, 0, 0))
hdr.append('// dz_status.png: %d x %d cells of %d px' % (cols, rows, S))
hdr.append('enum eDzSt { ' + ', '.join('DZST_%s = %d' % (n, i) for i, (n, _) in enumerate(cells)) + ', DZST_COUNT };')
hdr.append('static const int DZST_COLS = %d, DZST_ROWS = %d;' % (cols, rows))
for i, (n, p) in enumerate(cells): st.alpha_composite(fit(L(p), S, S), ((i % cols) * S, (i // cols) * S))
save(st, 'dz_status.png')

# ---- hud: dz_hud.png 1024 x 1024, named rects
hud = Image.new('RGBA', (1024, 1024), (0, 0, 0, 0)); rects = []
def put(name, im, x, y, w, h): hud.alpha_composite(fit(im, w, h), (x, y)); rects.append((name, x, y, w, h))
put('COMPASS_RING', L('gear/items/compassborder.png'), 0, 0, 256, 256)
put('COMPASS_ROSE', L('gear/items/compassarrow.png'), 256, 0, 256, 256)
put('GPS_FRAME', L('gear/items/gps.png'), 512, 0, 340, 274)
put('HEADER', L('gear/inventory/secondary.png'), 0, 256, 512, 128)
put('HOLDING', L('gear/inventory/holding.png'), 512, 280, 250, 97)
put('CARRYING', L('gear/inventory/carrying.png'), 762, 280, 250, 97)
put('BACKPACK', L('gear/inventory/backpack.png'), 512, 380, 250, 97)
put('PISTOL', L('gear/inventory/pistol.png'), 762, 380, 100, 100)
put('TROPHY', L('achievements/icons/achiev1.png'), 862, 380, 100, 100)
put('PLAYER', L('gear/items/player.png'), 962, 380, 35, 35)
put('BLIP', L('gear/items/blip/0.png'), 962, 420, 32, 32)
put('LOOT', L('gear/items/loot.png'), 962, 452, 32, 32)
for k, f in enumerate(['sold_icon', 'sold_crit', 'sold_tough', 'sold_dodge', 'med_icon', 'med_prof', 'med_scndchance', 'med_wbor',
                       'scav_icon', 'scav_good', 'scav_shadow', 'scav_camouflage', 'eng_icon', 'eng_ammo', 'eng_analysis', 'eng_duct']):
    put('SKILL_%s' % f.upper(), L('rpg/icons/%s.png' % f), (k % 8) * 64, 384 + (k // 8) * 64, 64, 64)
for k, f in enumerate(['fuel/%d' % v for v in (0, 20, 40, 60, 80, 100)]):
    put('FUEL%d' % k, L('status/vehicle/%s.png' % f), 520 + k * 20, 480, 16, 165)
for k, f in enumerate(['engine/eng_0', 'engine/eng_1', 'whl/whl_0', 'whl/whl_1', 'tank/tank_0', 'tank/tank_1', 'hull/hull_0', 'hull/hull_1', 'engine/mrot_0', 'engine/mrot_1']):
    put('VEH_%s' % f.split('/')[1].upper(), L('status/vehicle/%s.png' % f), 650 + (k % 2) * 44, 480 + (k // 2) * 24, 39, 19)
inv3 = L('gear/inventory/inventory3.png'); put('INV_DARK', inv3, 0, 512, 384, 512)
put('INV_PAPER', L('gear/inventory/inventory1.png'), 384, 660, 270, 364)
put('JOURNAL_ZK', L('journal/images/zombieskilled2.png'), 654, 660, 370, 92)
put('JOURNAL_HS', L('journal/images/headshots2.png'), 654, 752, 370, 92)
put('JOURNAL_MU', L('journal/images/murders2.png'), 654, 844, 370, 92)
put('JOURNAL_BK', L('journal/images/banditskilled2.png'), 654, 936, 370, 88)
hdr.append('// dz_hud.png 1024x1024: x, y, w, h')
hdr.append('struct DzRect { short x, y, w, h; };')
for n, x, y, w, h in rects: hdr.append('static const DzRect DZR_%s = { %d, %d, %d, %d };' % (n, x, y, w, h))
save(hud, 'dz_hud.png')

# ---- the radar / GPS / F11 world map (the MTA DayZ radarworld) and the journal + spawn selection art
save(L('gear/items/radarworld.png').convert('RGB').resize((2048, 2048), Image.LANCZOS), 'dz_map.png', colors=128)
save(L('journal/images/journal_page1.png').resize((1024, 700), Image.LANCZOS), 'dz_journal.png', colors=96)
save(L('spawnselection/spawnselection.png').convert('RGB').resize((1024, 512), Image.LANCZOS), 'dz_spawn.png', colors=128)
save(L('achievements/icons/bg_achievements.png').convert('RGB').resize((512, 396), Image.LANCZOS), 'dz_achbg.png', colors=64)
open(os.path.join(ROOT, 'src', 'mp_dayz_atlas.h'), 'w').write('\n'.join(hdr) + '\n')
print('header ok')
