#!/usr/bin/env python3
# MP 3.27 - builds src/ui/sa_map_data.h for the Google-style radar (mp_radar.inc).
#
# Inputs (all in this folder):
#   sa_nodes.json  every vehicle path node of San Andreas + links (eXo-MTA/ml_pathfind, test/sa_nodes.json)
#   water.dat      the game's water quads / triangles (GTA SA data/water.dat)
#   a_zones.inc    SA-MP zone names + boxes (gSAZones), used for the district labels and parks
#
# Output: one header with plain const arrays (no textures - the radar is drawn from vectors).
#   roads : nodes (x, y, z in 1/4 m), edges (node a, node b), a 24 x 24 grid of 250 m cells
#   water : convex polygons (3 or 4 corners, 1/4 m) with their height
#   labels: district names with a centre and a size (bigger zones show further out), park flag
import json, math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'ui', 'sa_map_data.h')
CELL = 250.0
GRID = 24          # -3000 .. 3000

def q(v): return int(round(v * 4.0))

nodes = json.load(open(os.path.join(HERE, 'sa_nodes.json')))
nodes.sort(key=lambda n: n['id'])
idmap = {n['id']: i for i, n in enumerate(nodes)}
edges = set()
for n in nodes:
    for t, _w in n['edges']:
        if t in idmap:
            a, b = idmap[n['id']], idmap[t]
            if a != b: edges.add((min(a, b), max(a, b)))
edges = sorted(edges)

# edge -> the cell of its midpoint (the drawing code looks one extra cell around the view)
cells = [[] for _ in range(GRID * GRID)]
for ei, (a, b) in enumerate(edges):
    mx = (nodes[a]['x'] + nodes[b]['x']) * 0.5; my = (nodes[a]['y'] + nodes[b]['y']) * 0.5
    cx = min(GRID - 1, max(0, int((mx + 3000) // CELL))); cy = min(GRID - 1, max(0, int((my + 3000) // CELL)))
    cells[cy * GRID + cx].append(ei)
cellStart, cellEdges = [], []
for c in cells:
    cellStart.append(len(cellEdges)); cellEdges.extend(c)
cellStart.append(len(cellEdges))

water = []
for line in open(os.path.join(HERE, 'water.dat')):
    p = line.split()
    if len(p) not in (22, 29): continue
    n = 4 if len(p) == 29 else 3
    v = [(float(p[i * 7]), float(p[i * 7 + 1]), float(p[i * 7 + 2])) for i in range(n)]
    if n == 4: v = [v[0], v[1], v[3], v[2]]          # file order is a 2 x 2 grid -> polygon order
    # counter-clockwise for the ImGui convex fill (any winding works, keep it consistent)
    area = sum(v[i][0] * v[(i + 1) % n][1] - v[(i + 1) % n][0] * v[i][1] for i in range(n))
    if area < 0: v = v[::-1]
    z = sum(c[2] for c in v) / n
    water.append((v, z))

# district labels: union of the zone boxes per name, label at the biggest box, size = sqrt(area)
zones = {}
skip = {'Los Santos', 'Las Venturas', 'San Fierro', 'Bone County', 'Tierra Robada', 'Red County',
        'Flint County', 'Whetstone', 'San Andreas'}
for m in re.finditer(r'\{"([^"]+)",\s*\{([-0-9., ]+)\}\}', open(os.path.join(HERE, 'a_zones.inc')).read()):
    name = m.group(1); b = [float(x) for x in m.group(2).split(',')]
    if name in skip: continue
    x0, y0, x1, y1 = b[0], b[1], b[3], b[4]
    zones.setdefault(name, []).append((x0, y0, x1, y1))
labels = []
parkNames = {'Glen Park', 'Pershing Square', 'Avispa Country Club', 'Yellow Bell Gol Course', 'Yellow Bell Golf Course',
             'Shady Creeks', 'Back o Beyond', 'Leafy Hollow', 'Missionary Hill', 'Mount Chiliad'}   # green on the map
for name, boxes in zones.items():
    best = max(boxes, key=lambda r: (r[2] - r[0]) * (r[3] - r[1]))
    total = sum((r[2] - r[0]) * (r[3] - r[1]) for r in boxes)
    cx = (best[0] + best[2]) * 0.5; cy = (best[1] + best[3]) * 0.5
    park = name in parkNames
    labels.append((name, cx, cy, math.sqrt(total), park, boxes if park else []))
labels.sort(key=lambda l: -l[3])
parks = [(r, name) for (name, _x, _y, _s, park, boxes) in labels if park for r in boxes]

def arr(name, ctype, vals, per=16):
    s = 'static const %s %s[%d] =\n{\n' % (ctype, name, len(vals))
    for i in range(0, len(vals), per):
        s += '    ' + ','.join(str(v) for v in vals[i:i + per]) + ',\n'
    return s + '};\n'

with open(OUT, 'w') as f:
    f.write('// Generated by tools/radar/gen_map.py - do not edit.\n')
    f.write('// San Andreas road network (vehicle path nodes), water and district names for the vector radar.\n')
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('#define SAMAP_CELL %.1ff\n#define SAMAP_GRID %d\n' % (CELL, GRID))
    f.write('#define SAMAP_NODES %d\n#define SAMAP_EDGES %d\n#define SAMAP_WATER %d\n#define SAMAP_LABELS %d\n#define SAMAP_PARKS %d\n\n'
            % (len(nodes), len(edges), len(water), len(labels), len(parks)))
    nv = []
    for n in nodes: nv += [q(n['x']), q(n['y']), q(n['z'])]
    f.write(arr('kSaMapNode', 'int16_t', nv, 24))
    ev = []
    for a, b in edges: ev += [a, b]
    f.write(arr('kSaMapEdge', 'uint16_t', ev, 24))
    f.write(arr('kSaMapCellStart', 'uint16_t', cellStart, 24))
    f.write(arr('kSaMapCellEdge', 'uint16_t', cellEdges, 24))
    f.write('struct SaMapWater { uint8_t n; int16_t z; int16_t x[4], y[4]; };\n')
    f.write('static const SaMapWater kSaMapWater[%d] =\n{\n' % len(water))
    for v, z in water:
        xs = [q(c[0]) for c in v] + [0] * (4 - len(v)); ys = [q(c[1]) for c in v] + [0] * (4 - len(v))
        f.write('    { %d, %d, { %s }, { %s } },\n' % (len(v), q(z), ','.join(map(str, xs)), ','.join(map(str, ys))))
    f.write('};\n')
    f.write('struct SaMapLabel { const char* name; float x, y, size; uint8_t park; };\n')
    f.write('static const SaMapLabel kSaMapLabel[%d] =\n{\n' % len(labels))
    for name, cx, cy, sz, park, _b in labels:
        f.write('    { "%s", %.1ff, %.1ff, %.1ff, %d },\n' % (name.replace('"', '\\"'), cx, cy, sz, 1 if park else 0))
    f.write('};\n')
    f.write('struct SaMapRect { float x0, y0, x1, y1; };\n')
    f.write('static const SaMapRect kSaMapPark[%d] =\n{\n' % max(1, len(parks)))
    for r, _n in parks: f.write('    { %.1ff, %.1ff, %.1ff, %.1ff },\n' % r)
    if not parks: f.write('    { 0, 0, 0, 0 },\n')
    f.write('};\n')
print('nodes', len(nodes), 'edges', len(edges), 'water', len(water), 'labels', len(labels), 'parks', len(parks), '->', OUT)
