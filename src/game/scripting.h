// Embedded script-opcode executor (same technique as SAUtils / ReSAMP by RusJJ).
// Lets libMP run without a hard SAUtils dependency.
#pragma once
#include <stdint.h>

#define MAX_SCRIPT_VARS 16

struct SCRIPT_COMMAND
{
    uint16_t opCode;
    char     params[MAX_SCRIPT_VARS];
};

#define DEFOPCODE(__opcode, __name, __args) static const SCRIPT_COMMAND scm_##__name = { 0x##__opcode, #__args }
#define CALLSCM(__name, ...) Scripting::Command(&scm_##__name, ##__VA_ARGS__)

namespace Scripting
{
    bool Init(void* gameHandle);
    bool IsReady();
    int  Command(const SCRIPT_COMMAND* cmd, ...);
}

